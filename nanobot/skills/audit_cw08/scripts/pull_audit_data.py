def main():
    parser = argparse.ArgumentParser(
        description="CW08 流程审计数据拉取脚本",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""示例:
    uv run nanobot/skills/audit_cw08/scripts/pull_audit_data.py --request-id 13217158
    uv run nanobot/skills/audit_cw08/scripts/pull_audit_data.py 13217158""",
    )
    parser.add_argument(
        "request_id",
        nargs="?",
        help="流程编号（如 13217158）",
    )
    parser.add_argument(
        "--request-id",
        dest="request_id_flag",
        help="流程编号（如 13217158），等同于直接传入参数",
    )

    args = parser.parse_args()

    # 优先使用 --request-id 参数，否则使用位置参数
    request_id = args.request_id_flag or args.request_id

    if not request_id:
        parser.error("必须提供 request_id 参数")

    # 执行数据拉取
    result = pull_data_json(request_id)

    # 输出 JSON 结果
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()